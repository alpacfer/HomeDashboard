// Claude Code PreToolUse hook: refuses Edit/Write on files that are generated
// or must be changed by a tool, and says which tool. Wired in
// .claude/settings.json; the list mirrors "Do not touch without being asked"
// in AGENTS.md. Exit code 2 blocks the tool call and shows the message.

import { readFileSync } from 'node:fs';
import path from 'node:path';

const PROTECTED = [
  [/^public\/facts\/daily\/.+\.json$/, 'generated by npm run facts:generate. Edit data/daily-fact-overrides.json and rerun it (docs/DAILY_FACTS.md).'],
  [/^public\/fonts\/clock\//, 'generated by npm run fonts:clock. Edit the face list in scripts/fetch-clock-fonts.mjs and rerun it (docs/CLOCK.md).'],
  [/^app\/clock-fonts\.css$/, 'generated by npm run fonts:clock. Edit the face list in scripts/fetch-clock-fonts.mjs and rerun it (docs/CLOCK.md).'],
  [/^package-lock\.json$/, 'written by npm. Change package.json and run npm install, never edit the lockfile by hand.'],
  [/^render\.yaml$/, 'the record of a service created through the Render dashboard, which is the source of truth. Change the dashboard first, then bring this file to match it (docs/DEPLOYMENT.md).'],
];

// The other two entries in AGENTS.md's "Do not touch" list -- lib/transit.ts's
// stop names and lib/transitous.ts's headsigns -- are deliberately not here.
// Both files are mostly ordinary logic, and blocking every edit to them to
// protect a table of strings would cost more than it saves. check-rules.mjs
// keeps this list and that section of AGENTS.md in step instead, so the two
// descriptions of the same rule cannot drift the way they had.

let input = {};
try { input = JSON.parse(readFileSync(0, 'utf8')); } catch { process.exit(0); }
const target = input.tool_input?.file_path ?? input.tool_input?.notebook_path;
if (!target) process.exit(0);
const root = process.env.CLAUDE_PROJECT_DIR ?? process.cwd();
const relative = path.relative(root, path.resolve(root, target)).split(path.sep).join('/');
for (const [pattern, reason] of PROTECTED) {
  if (pattern.test(relative)) {
    console.error('Blocked: ' + relative + ' is ' + reason + ' If Alejandro explicitly asked for a hand edit here, say so and do it through Bash.');
    process.exit(2);
  }
}
